"""ORM models (SQL tables).

Tables are created by the scripts in `db/init/`, not by the application.
"""

from sqlmodel import Field, SQLModel


class User(SQLModel, table=True):
    """Person allowed to log in to the API."""

    __tablename__ = "users"

    id: int | None = Field(default=None, primary_key=True)
    login: str = Field(unique=True)
    password_hash: str  # bcrypt hash generated by pgcrypto: crypt(..., gen_salt('bf'))
